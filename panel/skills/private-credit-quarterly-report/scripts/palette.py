# ⛔ E56/E57/E58（median_band）和 E51/E52（轨迹图）都是三只基金同图。
#    HILITE 打头，另外两只取**位 3** 和**位 6** —— 位 6 是紫，正好符合「紫只在最不
#    重要的位次出现」。⛔ 不许取位 2（那就是 HILITE 自己）、不许取位 1（中位数线在用）。
