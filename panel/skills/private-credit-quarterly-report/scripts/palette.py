#     ⚠ 位次一动，下面所有「按位次取色」的角色名跟着变（名字只是别名，位次才是真值）——
#       第 2 位那 34 处（右轴线 / 第二组柱）从蓝灰变成青绿，这就是「亮绿重要性提高」；
#       紫从第 4 位退到第 6 位，只在用满六色的图里才出现，这就是「紫重要性下降」。
SERIES = [C1, C3, C2, C5, C6, C4]     # ⭐ 多序列图一律 SERIES[i]，顺序由这里定


# ── 切片超过 6 个时的淡化版（Alex 2026-08-25 允许「用六色的淡化版」）──────────
# ⛔ 只允许**沿这六色向白色混**，不许引入新色相。混合比例写死，保证跨季同一个位次
#    永远是同一个颜色（不许按当季切片数动态调）。
#    第 1–6 位：原色；第 7–12 位：混白 52%；第 13–18 位：混白 76%。
#    12 色之内足够 —— 2026Q3 最多的是 E39 的 25 个 GICS 子行业，那张不是饼图。
def _mix_white(hexcol, f):
    r, g, b = (int(hexcol[i:i + 2], 16) for i in (1, 3, 5))
    m = lambda c: round(c + (255 - c) * f)
    return '#%02X%02X%02X' % (m(r), m(g), m(b))


TINTS = [0.0, 0.52, 0.76]           # 三档，位次每满 6 个降一档
SERIES_EXT = [_mix_white(c, f) for f in TINTS for c in SERIES]


def series_ext(n):
    """要 n 个可区分的颜色：前 6 原色，之后按 TINTS 逐档淡化。

    ⛔ 超过 len(SERIES_EXT)（18）就报错,不许静默循环 —— 循环会让两块同色
    （2026-08-25 实测:pie 用 SERIES[i % 6],第 7 片与第 1 片撞色）。
    """
    if n > len(SERIES_EXT):
        raise SystemExit(f'✗ 要 {n} 个颜色,但六色 × {len(TINTS)} 档只有 {len(SERIES_EXT)} 个。'
                         f'\n  这种切片数不该用饼图 —— 换成柱图,或把尾部并成 Others。')
    return SERIES_EXT[:n]

