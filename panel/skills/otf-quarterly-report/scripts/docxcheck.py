#!/usr/bin/env python3
"""阶段二成稿版面自查 —— 对着 v3 实测基准查最终 docx。

    python3 docxcheck.py OTF_2026Q3_OTF update_v4.docx

基准全部来自 v3（`OTF_2026Q3_OTF update_v3.docx`）的 document.xml 实测值，不是猜的：
  A4 竖版 11906×16838 twips、左右边距 830/832 = 1.15 in、正文可用宽 7.12 in、
  图片插入宽 6.05 in（正文宽的 85%，居中）、一个 A4 横版节（16838×11906，可用宽 10.54 in）。
不通过就 exit 1。
"""
import os, re, sys, zipfile, io

A4_P = (11906, 16838)
A4_L = (16838, 11906)
MAR_L, MAR_R = 830, 832
IMG_W = 6.05            # in，常规图：画布宽 = 插入宽 = 正文宽 7.12 in 的 85%，居中
IMG_W_FULL = 7.11       # in，⭐ 例外：封面顶部那条长横条，与正文两端同宽
N_FULL = 1              # 与正文同宽的图正好 1 张（封面横条）
IMG_W_PAIR = 3.50       # in，阶段二并排的插入宽度
N_PAIR = 10             # 并排的图正好 10 张：2.6.2 图10‖11、2.6.3 图13‖14、3.3 图15‖16/17‖18/19‖20
BODY_COLOR = '000000'   # 正文字体颜色：纯黑
IMG_TOL = 0.04
TBL_FONT, TBL_SZ = 'Arial', 16      # 所有表格统一 Arial 8pt（sz 半点 = 16）
BANNED = ['To be written', 'to be written', 'Valuation attribution',
          '待补', '本节留空', 'TBD', 'not generated by this pipeline']
BODY_FONT = 'Calibri Light'
BODY_SZ = 24            # 半点 = 12 pt = 小四
EMU = 914400

fails, warns, oks = [], [], []


def ok(m):   oks.append(m)
def bad(m):  fails.append(m)
def warn(m): warns.append(m)


def main(path):
    if not os.path.exists(path):
        sys.exit(f'找不到文件：{path}')
    z = zipfile.ZipFile(path)
    doc = z.read('word/document.xml').decode('utf-8')

    # ── 1. 分节：纸张与边距 ────────────────────────────────────────
    secs = re.findall(r'<w:pgSz[^/]*/>', doc)
    n_land = 0
    for i, t in enumerate(secs, 1):
        w = int(re.search(r'w:w="(\d+)"', t).group(1))
        h = int(re.search(r'w:h="(\d+)"', t).group(1))
        land = bool(re.search(r'w:orient="landscape"', t))
        if land:
            n_land += 1
            if (w, h) == A4_L:
                ok(f'第 {i} 节 A4 横版 {w}×{h}')
            else:
                bad(f'第 {i} 节标了 landscape 但尺寸 {w}×{h} 不是 A4 横版 {A4_L[0]}×{A4_L[1]}')
        else:
            if (w, h) == A4_P:
                ok(f'第 {i} 节 A4 竖版 {w}×{h}')
            else:
                bad(f'第 {i} 节 {w}×{h} 不是 A4 竖版 {A4_P[0]}×{A4_P[1]}'
                    f'（{w/1440:.2f}×{h/1440:.2f} in）')
    if n_land == 0:
        warn('没有横版节 —— 2.6.1 的 T9 六家竞品表放得下吗？')
    elif n_land == 1:
        ok('恰好一个横版节（2.6.1 BDC competitor）')
    else:
        bad(f'有 {n_land} 个横版节，只应该有 1 个（2.6.1）')

    for t in re.findall(r'<w:pgMar[^/]*/>', doc):
        l = int(re.search(r'w:left="(\d+)"', t).group(1))
        r = int(re.search(r'w:right="(\d+)"', t).group(1))
        if (l, r) != (MAR_L, MAR_R):
            bad(f'边距 left={l} right={r}，基准是 {MAR_L}/{MAR_R}（合计 1.15 in）')
    if not fails or all('边距' not in f for f in fails):
        ok(f'左右边距 {MAR_L}/{MAR_R} = 1.15 in，正文可用宽 7.12 in，图片 {IMG_W} in = 85%')

    # ── 2. 正文字体：不许残留 Arial 之类的 run 级覆盖 ──────────────
    st = z.read('word/styles.xml').decode('utf-8')
    m = re.search(r'<w:docDefaults>.*?</w:docDefaults>', st, re.S)
    dd = m.group(0) if m else ''
    if f'w:ascii="{BODY_FONT}"' in dd:
        ok(f'docDefaults 字体 = {BODY_FONT}')
    else:
        bad(f'docDefaults 字体不是 {BODY_FONT}')
    dsz = re.search(r'<w:sz w:val="(\d+)"/>', dd)
    if dsz and int(dsz.group(1)) != BODY_SZ:
        warn(f'docDefaults 字号 {int(dsz.group(1))/2:g} pt，正文靠 run 覆盖到 '
             f'{BODY_SZ/2:g} pt 才对得上小四')

    ascii_fonts = re.findall(r'w:ascii="([^"]+)"', doc)
    othr = sorted({f for f in ascii_fonts if f != BODY_FONT})
    if othr:
        from collections import Counter
        cnt = Counter(f for f in ascii_fonts if f != BODY_FONT)
        bad(f'正文 run 里有 {sum(cnt.values())} 处非 {BODY_FONT} 字体覆盖：'
            + '、'.join(f'{k}×{v}' for k, v in cnt.most_common(4))
            + f' —— docDefaults 写了 {BODY_FONT} 也没用，run 级覆盖优先')
    else:
        ok(f'正文 run 里没有非 {BODY_FONT} 的字体覆盖')

    # 正文字体颜色必须纯黑
    cols = re.findall(r'<w:color w:val="([0-9A-Fa-f]{6})"', doc)
    if cols:
        from collections import Counter
        cc = Counter(c.upper() for c in cols)
        nonblack = {k: v for k, v in cc.items() if k != BODY_COLOR.upper()}
        # 标题/脚注/表头允许有自己的颜色，所以只在「纯黑不是最常见色」时报错
        top = cc.most_common(1)[0][0]
        if top != BODY_COLOR.upper():
            bad(f'最常见的字体颜色是 #{top}（{cc[top]} 处），正文应为纯黑 #{BODY_COLOR} '
                f'—— 早前的 #22303C 已作废')
        else:
            ok(f'正文字体颜色 = 纯黑 #{BODY_COLOR}（{cc[top]} 处）')
        leftover = {k: v for k, v in nonblack.items() if v > 20}
        if leftover:
            warn('还有较多非纯黑的着色（可能是标题/表头/脚注，确认一下不是正文）：'
                 + '、'.join(f'#{k}×{v}' for k, v in sorted(leftover.items(),
                                                            key=lambda x: -x[1])[:5]))
    else:
        warn('文档里没有显式的 <w:color>，正文颜色继承样式 —— 确认样式里是纯黑')

    szs = [int(x) for x in re.findall(r'<w:sz w:val="(\d+)"/>', doc)]
    if szs:
        top = max(set(szs), key=szs.count)
        if top == BODY_SZ:
            ok(f'最常见字号 = {BODY_SZ/2:g} pt（小四），{szs.count(top)} 处')
        else:
            bad(f'最常见字号是 {top/2:g} pt（{szs.count(top)} 处），正文应为 {BODY_SZ/2:g} pt 小四')

    # ── 3. 图片插入宽度 + 1:1 ────────────────────────────────────
    rels = z.read('word/_rels/document.xml.rels').decode('utf-8')
    rmap = dict(re.findall(r'Id="(rId\d+)"[^>]*Target="([^"]+)"', rels))
    blocks = re.findall(r'<wp:extent cx="(\d+)" cy="(\d+)"/>.*?r:embed="(rId\d+)"', doc, re.S)
    if not blocks:
        warn('文档里一张图都没有')
    try:
        from PIL import Image
        have_pil = True
    except ImportError:
        have_pil = False
        warn('没装 Pillow，跳过 1:1 检查（只查插入宽度）')

    narrow, off, pairs = [], [], []
    for i, (cx, cy, rid) in enumerate(blocks, 1):
        w_in = int(cx) / EMU
        name = os.path.basename(rmap.get(rid, '?'))
        near = min((IMG_W, IMG_W_FULL, IMG_W_PAIR), key=lambda t: abs(w_in - t))
        if abs(w_in - near) > IMG_TOL:
            off.append(f'图{i} {name} 插入宽 {w_in:.2f} in')
        if not have_pil:
            continue
        tgt = 'word/' + rmap.get(rid, '').lstrip('/')
        try:
            px = Image.open(io.BytesIO(z.read(tgt))).width
        except Exception:
            continue
        # 1:1 判据：落盘画布宽（px/200dpi）应等于插入宽
        canvas = px / 200
        eff = 7.5 * w_in / canvas          # 图内 7.5 pt 的字在纸上的实际字号
        is_pair = abs(w_in - IMG_W_PAIR) <= IMG_TOL
        is_full = abs(w_in - IMG_W_FULL) <= IMG_TOL
        want_canvas = IMG_W_FULL if is_full else IMG_W
        if abs(canvas - want_canvas) > 0.15:
            narrow.append(f'图{i} {name}：画布 {canvas:.2f} in，应为 {want_canvas} in'
                          f'（插 {w_in:.2f} in，图内 7.5 pt 显示 {eff:.1f} pt）')
        elif is_pair:
            pairs.append(f'图{i} {name}：并排插 {w_in:.2f} in，图内 7.5 pt 显示 {eff:.1f} pt')
    if off:
        bad(f'{len(off)} 张图插入宽度不在允许的三档里（{IMG_W} 单图 / {IMG_W_FULL} 封面横条 / '
            f'{IMG_W_PAIR} 并排）：' + '；'.join(off[:6]) + ('…' if len(off) > 6 else ''))
    else:
        n_pair = sum(1 for cx, _, _ in blocks if abs(int(cx)/EMU - IMG_W_PAIR) <= IMG_TOL)
        n_full = sum(1 for cx, _, _ in blocks if abs(int(cx)/EMU - IMG_W_FULL) <= IMG_TOL)
        n_solo = len(blocks) - n_pair - n_full
        ok(f'全部 {len(blocks)} 张图插入宽度合规（单图 {n_solo} × {IMG_W} in / '
           f'封面横条 {n_full} × {IMG_W_FULL} in / 并排 {n_pair} × {IMG_W_PAIR} in）')
        if n_pair != N_PAIR:
            bad(f'并排图有 {n_pair} 张，应该正好 {N_PAIR} 张 —— '
                f'2.6.2 的图 10‖11、2.6.3 的图 13‖14、3.3 的图 15‖16 / 17‖18 / 19‖20，'
                f'其余全部 {IMG_W} in 单图')
        if n_full != N_FULL:
            bad(f'与正文同宽（{IMG_W_FULL} in）的图有 {n_full} 张，应该正好 {N_FULL} 张 —— '
                f'只有封面顶部那条长横条不走 85%')
    if narrow:
        bad(f'{len(narrow)} 张图的画布不是 {IMG_W} in（阶段一出图的画布是写死的）：\n      '
            + '\n      '.join(narrow[:8]) + ('\n      …' if len(narrow) > 8 else ''))
    elif have_pil:
        ok(f'全部图画布 = {IMG_W} in（正文宽的 85%），单图是 1:1')
    for m_ in pairs:
        warn(m_ + ' —— 记得说明与分析合并放在两图下方')

    # ── 4. 表头跨页重复 ──────────────────────────────────────────
    n_tbl = doc.count('<w:tbl>')
    n_hdr = doc.count('<w:tblHeader')
    if n_tbl == 0:
        warn('文档里一张表都没有')
    elif n_hdr >= n_tbl:
        ok(f'{n_tbl} 张表都带 w:tblHeader（表头跨页重复）')
    else:
        bad(f'{n_tbl} 张表里只有 {n_hdr} 张带 w:tblHeader —— '
            f'剩下 {n_tbl - n_hdr} 张跨页后看不到列名')

    # ── 5. 报告季度 RQ：文件名 / 页眉 必须一致，且不等于数据季度 ──────
    import glob as _g
    fn_q = re.search(r'(20\d\d)Q([1-4])', os.path.basename(path))
    hdr_qs = set()
    for n in z.namelist():
        if re.match(r'word/header\d*\.xml$', n):
            t = ' '.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', z.read(n).decode('utf-8')))
            hdr_qs |= set(re.findall(r'20\d\dQ[1-4]', t))
    if not fn_q:
        bad('文件名里没有 <YYYY>Q<n> —— 命名规则是 '
            'OTF_<报告季度>_OTF update_v<n>.docx，报告季度按撰写时间')
    else:
        rq = fn_q.group(0)
        if hdr_qs and hdr_qs != {rq}:
            bad(f'文件名季度 {rq} 与页眉季度 {sorted(hdr_qs)} 不一致 —— 两处都必须是撰写季度')
        else:
            ok(f'报告季度 {rq}：文件名与页眉一致')
        # 数据季度应当比报告季度早一季（季报滞后），若相同大概率是把 CQ 当 RQ 用了
        yy = int(rq[2:4]); qn = int(rq[-1])
        cq_tag = f'{qn}Q{yy:02d}'
        if re.search(r'\b' + cq_tag + r'\b', doc):
            warn(f'正文/图里出现了 {cq_tag}，与报告季度 {rq} 同期 —— '
                 f'确认这是真有当季 filing，而不是把撰写季度当成了数据季度')

    # ── 6. Summary 与 1. News 之间的硬分页 ──────────────────────────
    m = re.search(r'<w:p\b(?:(?!</w:p>).)*?<w:t[^>]*>\s*1[\.\s]*News', doc, re.S)
    if not m:
        warn('没找到「1. News」标题段，跳过分页检查')
    else:
        para = doc[m.start():doc.index('</w:p>', m.start())]
        if '<w:pageBreakBefore' in para or 'w:type="page"' in para:
            ok('Summary 与 1. News 之间有硬分页，News 另起一页')
        else:
            prev_end = doc.rfind('</w:p>', 0, m.start())
            prev = doc[doc.rfind('<w:p ', 0, prev_end):prev_end] if prev_end > 0 else ''
            if 'w:type="page"' in prev:
                ok('Summary 段末有分页符，News 另起一页')
            else:
                bad('Summary 与 1. News 之间没有分页符 —— '
                    'News 必须另起一页（给标题段加 <w:pageBreakBefore/> 最稳）')

    # ── 7. 表格字体：统一 Arial 8pt ─────────────────────────────────
    tbls = re.findall(r'<w:tbl>.*?</w:tbl>', doc, re.S)
    bad_f, bad_s = set(), set()
    for t in tbls:
        for f_ in re.findall(r'w:ascii="([^"]+)"', t):
            if f_ != TBL_FONT:
                bad_f.add(f_)
        for z_ in re.findall(r'<w:sz w:val="(\d+)"/>', t):
            if int(z_) != TBL_SZ:
                bad_s.add(int(z_))
    if not tbls:
        pass
    elif bad_f or bad_s:
        det = []
        if bad_f: det.append('字体 ' + '、'.join(sorted(bad_f)))
        if bad_s: det.append('字号 ' + '、'.join(f'{x/2:g}pt' for x in sorted(bad_s)))
        bad(f'表格里有非 {TBL_FONT} {TBL_SZ/2:g}pt 的设置：' + '；'.join(det)
            + ' —— 全部 14 张表统一 Arial 8 号')
    else:
        ok(f'{len(tbls)} 张表全部 {TBL_FONT} {TBL_SZ/2:g}pt')

    # ── 8. News 来源：真超链接 + 完整文章 URL，不许裸域名 ─────────────
    links = re.findall(r'Type="[^"]*/hyperlink"[^>]*Target="([^"]+)"', rels)
    if not links:
        bad('文档里一个外部超链接都没有 —— News 每条的来源必须是超链接')
    else:
        def bare(u):
            m2 = re.match(r'https?://[^/]+(/?.*)$', u)
            return (m2 is None) or (m2.group(1).strip('/') == '')
        vague = sorted({u for u in links if bare(u)})
        if vague:
            bad(f'{len(vague)} 个来源链接只到域名，没到文章：'
                + '、'.join(vague[:6]) + ('…' if len(vague) > 6 else '')
                + ' —— 必须是那一篇的完整 URL，拿不到就不要写这条新闻')
        else:
            ok(f'{len(links)} 个来源链接都带路径（指向具体文章）')

    # ── 9. 禁用占位与 Valuation 归因 ────────────────────────────────
    body = ' '.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', doc))
    hit = [b for b in BANNED if b in body]
    if hit:
        bad('正文里出现了占位/禁用字样：' + '、'.join(sorted(set(hit)))
            + ' —— Things we should know 写不出来就整节删掉，2.7 不要 Valuation')
    else:
        ok('没有 To be written / Valuation attribution 之类的占位')

    # ── 输出 ────────────────────────────────────────────────────
    print(f'\n=== 版面自查 · {os.path.basename(path)} ===\n')
    for m in oks:    print('  ✓', m)
    for m in warns:  print('  ?', m)
    for m in fails:  print('  ✗', m)
    print(f'\n通过 {len(oks)}　不通过 {len(fails)}　待确认 {len(warns)}')
    if fails:
        print('\n不通过就不能交稿。改完再跑一遍。')
        return 1
    return 0


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
